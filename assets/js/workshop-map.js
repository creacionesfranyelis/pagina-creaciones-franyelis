(() => {
  'use strict';
  const init = () => {
    const stage = document.getElementById('workshop-map-stage');
    const button = document.getElementById('load-workshop-map');
    const placeholder = document.getElementById('workshop-map-placeholder');
    const status = document.getElementById('workshop-map-status');
    const consent = window.FranyelisConsent;
    if (!stage || !button || !placeholder || !consent) return;
    // Keep the workshop information and map actions clear of mobile floating controls.
    const section = stage.closest('.workshop-map');
    if (section && typeof window.IntersectionObserver === 'function') {
      const visibility = new IntersectionObserver(entries => {
        document.body.classList.toggle('workshop-map-in-view', entries.some(entry => entry.isIntersecting));
      }, { threshold: 0 });
      visibility.observe(section);
    }
    // Official embed generated by Google Maps for the confirmed workshop address.
    const embed = 'https://www.google.com/maps/embed?pb=!1m18!1m12!1m3!1d3086.0616651375503!2d-70.6918022!3d-33.454891499999995!2m3!1f0!2f0!3f0!3m2!1i1024!2i768!4f13.1!3m3!1m2!1s0x9662c4f4dfcc5c33%3A0xf0a9a674a46efc44!2sToro%20Mazote%2076%2C%209160097%20Estaci%C3%B3n%20Central%2C%20Regi%C3%B3n%20Metropolitana!5e1!3m2!1ses!2scl!4v1791535893804!5m2!1ses!2scl';
    let requested = false;
    let frame = null;
    const unload = () => {
      frame?.remove();
      frame = null;
      requested = false;
      placeholder.hidden = false;
      button.disabled = false;
      stage.removeAttribute('aria-busy');
      status.textContent = 'El mapa está desactivado. El enlace Cómo llegar sigue disponible.';
    };
    const load = () => {
      if (!requested || frame || !consent.has('externalMap')) return;
      frame = document.createElement('iframe');
      frame.title = 'Ubicación del taller: Toro Mazote 76, Estación Central';
      frame.referrerPolicy = 'no-referrer';
      frame.width = '600';
      frame.height = '450';
      frame.setAttribute('allowfullscreen', '');
      stage.setAttribute('aria-busy', 'true');
      button.disabled = true;
      status.textContent = 'Cargando Google Maps. También puedes usar Cómo llegar.';
      frame.addEventListener('load', () => {
        stage.removeAttribute('aria-busy');
        status.textContent = 'Google Maps está habilitado. Si no ves el mapa, utiliza Cómo llegar.';
      }, { once: true });
      frame.addEventListener('error', () => {
        unload();
        status.textContent = 'No se pudo cargar el mapa. Utiliza Cómo llegar o vuelve a intentarlo.';
      }, { once: true });
      frame.src = embed;
      stage.append(frame);
      placeholder.hidden = true;
    };
    button.addEventListener('click', () => {
      requested = true;
      // This explicit button authorizes Google Maps only; marketing stays unchanged.
      if (!consent.has('externalMap')) {
        consent.update({ marketing: consent.has('marketing'), externalMap: true });
      }
      load();
    });
    consent.subscribe(() => {
      if (!consent.has('externalMap')) unload();
      else load();
    });
  };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init, { once: true });
  else init();
})();
